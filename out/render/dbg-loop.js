const L = window.squaringLab, $ = id => document.getElementById(id);
L.R.warmOn = false;
const sleep = ms => new Promise(r => setTimeout(r, ms));
const idle = async () => { while (!L.idle()) await sleep(8); };
await idle(); await sleep(200);
const out = [];
let gaps = [], last = performance.now(), on = true;
(function tick() { const t = performance.now(); gaps.push(t - last); last = t; if (on) requestAnimationFrame(tick); })();
const run = async (name, fn) => {
  await idle(); await sleep(200);
  L.R.loopMax = 0; L.R.log = []; gaps = []; last = performance.now();
  const t0 = performance.now(); fn(); await sleep(60); await idle();
  const bands = L.R.log.filter(x => x[0] === 'band'), sum = i => bands.reduce((a, x) => a + x[i], 0);
  gaps.sort((a, b) => b - a);
  out.push(`${name}: ${Math.round(performance.now() - t0)} ms, longest loop() ${L.R.loopMax.toFixed(2)} ms in ${L.R.loopWhere}, frame gaps top3 ${gaps.slice(0, 3).map(x => x.toFixed(1)).join(' ')}, bands ${bands.length}, GPU busy ${(100 * sum(3) / Math.max(1, sum(2))).toFixed(0)}% of band time, largest band GPU ${Math.max(...bands.map(x => x[3])).toFixed(1)} ms`);
};
const idx = id => +$('ap-' + id).value;
await run('camera move', () => { L.cam.yaw += 0.2; L.touch(); });
await run('approach -> classic', () => { L.S.approach = idx('classic'); L.touch(); });
await run('equation -> lambda', () => { L.S.eq = 'c*z*(1 - z)'; L.S.z0 = '0.5'; L.touch(); });
await run('mode -> Kleinian', () => { L.S.mode = 'k'; L.touch(); });
on = false;
return out;
